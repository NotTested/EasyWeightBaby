import { test } from "node:test";
import assert from "node:assert/strict";
import { importFixture } from "./helpers/import-fixture";
import { reviewTemplate, validateReview, reviewHash } from "../src/lib/import-review";
test("review decisions bind exact staging, source identity and every review issue", () => {
 const input = importFixture(), template = reviewTemplate(input);
 assert.equal(template.decisions[0].decision, "defer");
 assert.equal(validateReview(input, template).reviewed.length, 0);
 const reviewed = structuredClone(template) as { format: 1; archiveHash: string; stagingHash: string; decisions: Array<{ sourceRef: string; sourceType: "exercises"; externalId: string | null; contentHash: string; decision: "defer" | "reviewed"; resolutions: Array<{ issueIndex: number; note: string }> }> };
 reviewed.decisions[0].decision = "reviewed";
 assert.equal(validateReview(input, reviewed).reviewed.length, 1);
 assert.throws(() => validateReview(input + " ", reviewed));
 assert.throws(() => validateReview(input, { ...reviewed, ownerId: "other" }));
 assert.throws(() => validateReview(input, { ...reviewed, decisions: [] }));
 const tampered = structuredClone(reviewed); tampered.decisions[0].externalId = "c".repeat(32);
 assert.throws(() => validateReview(input, tampered));
 const stage = JSON.parse(input); stage.issues.push({ code: "side_review", source: stage.records.exercises[0].source, severity: "review" });
 const text = JSON.stringify(stage), plan = reviewTemplate(text);
 const candidate = { ...plan, decisions: plan.decisions.map(d => ({ ...d, decision: "reviewed", resolutions: [] as Array<{issueIndex: number; note: string}> })) };
 assert.throws(() => validateReview(text, candidate));
 candidate.decisions[0].resolutions = [{ issueIndex: 0, note: "Synthetic review only; no production approval" }];
 assert.equal(validateReview(text, candidate).reviewed.length, 1);
 candidate.decisions[0].resolutions[0].issueIndex = 99; assert.throws(() => validateReview(text, candidate));
 stage.records.exercises[0].notionId = null;
 const unknownText = JSON.stringify(stage), unknown = reviewTemplate(unknownText);
 unknown.decisions[0].decision = "reviewed" as "defer";
 assert.throws(() => validateReview(unknownText, unknown));
 assert.equal(reviewHash({ b: 2, a: 1 }), reviewHash({ a: 1, b: 2 }));
});
